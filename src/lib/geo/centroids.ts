/** Lower case, accents, apostrophes and punctuation removed, "&" read as "and", no leading "the". */
function normalise(name: string) {
  return name
    .normalize('NFKD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/['‘’`]/g, '')
    .replace(/&/g, ' and ')
    .replace(/[^a-z0-9]+/g, ' ')
    .trim()
    .replace(/^the /, '');
}

const INDEX = new Map<string, readonly [number, number]>();
for (const [name, centre] of Object.entries(CENTROIDS)) INDEX.set(normalise(name), centre);
for (const [alias, name] of Object.entries(ALIASES)) INDEX.set(normalise(alias), CENTROIDS[name]);

export function centroidOf(country: string): readonly [number, number] | undefined {
  return INDEX.get(normalise(country));
}

/** The names in a list that the globe cannot place, for editors to correct. */
export function unplacedCountries(names: string[]): string[] {
  return names.filter((name) => !centroidOf(name));
}
